/**
 * @param {string} normalizedQuestion
 * @return {string} — дополнительные термины через пробел
 */
export function expandSynonyms(normalizedQuestion) {
    const extra = [];
    SYNONYMS.forEach(([re, terms]) => {
        if (re.test(normalizedQuestion)) {
            extra.push(terms);
        }
    });
    return extra.join(' ');
}

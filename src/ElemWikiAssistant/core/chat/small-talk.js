/**
 * Короткие реплики без обращения к модели: приветствия, благодарности, «понятно», прощания,
 * вопросы о самом помощнике («кто ты», «что умеешь»).
 * Срабатывает, только если всё сообщение — по сути одна такая фраза (не длиннее 4 слов).
 */

const HINT = 'Спросите что-нибудь о руководстве — например, как настроить виджет.';

/** @type {Array<{ re: RegExp, reply: string }>} */
const RULES = [
    {
        re: /^(?:(?:всем\s+)?привет(?:ик|ствую)?|здравствуй(?:те)?|добр(?:ый|ого)\s+(?:день|дня|вечер|вечера)|доброе\s+утро|доброго\s+утра|хай|hi|hello|hey|good\s+(?:morning|afternoon|evening))(?:\s+(?:всем|там|there|everyone))?$/,
        reply: `Здравствуйте! ${HINT}`
    },
    {
        re: /^(?:(?:большое\s+|огромное\s+)?спасибо(?:\s+(?:большое|огромное|за\s+помощь))?|благодарю|спс|пасиб[оа]?|thanks?(?:\s+(?:a\s+lot|you))?|thank\s+you(?:\s+very\s+much)?|thx)$/,
        reply: 'Пожалуйста! Если появятся ещё вопросы по руководству — спрашивайте.'
    },
    {
        re: /^(?:ок(?:ей)?|окей|ok(?:ay)?|понятно|ясно|хорошо|понял[а]?|ладно|отлично|супер|got\s+it)(?:\s*,?\s*(?:спасибо|понятно|ясно|хорошо|thanks))?$/,
        reply: `Отлично! ${HINT}`
    },
    {
        re: /^(?:а\s+)?(?:ты\s+)?(?:кто\s+ты(?:\s+такой)?|что\s+ты\s+(?:умеешь|можешь)|что\s+(?:умеешь|можешь)|чем\s+(?:ты\s+)?(?:можешь\s+)?помочь|ты\s+кто|who\s+are\s+you|what\s+can\s+you\s+do|help|помощь)$/,
        reply:
            'Я AI-помощник по руководству Insight. Отвечаю на вопросы о работе в редакторе и настройке виджетов ' +
            'по тексту этой вики и даю ссылки на страницы, где написано подробнее. ' +
            'Например: «как настроить фильтр по дате» или «как выгрузить данные в Excel».'
    },
    {
        re: /^(?:пока(?:-пока)?|до\s+свидания|до\s+встречи|всего\s+доброго|bye(?:-bye)?|goodbye|see\s+you)$/,
        reply: 'До свидания! Возвращайтесь, если понадобится помощь с руководством.'
    }
];

/**
 * Ответ на короткую реплику или `null`, если это не small talk.
 *
 * @param {string} text
 * @return {string|null}
 */
export function matchSmallTalk(text) {
    const clean = String(text || '')
        .toLowerCase()
        .replace(/ё/g, 'е')
        // эмодзи, знаки препинания и символы (дефис внутри слова сохраняется)
        .replace(/[^\p{L}\p{N}\s-]+/gu, ' ')
        .replace(/\s+/g, ' ')
        .trim()
        .replace(/^-+|-+$/g, '')
        .trim();
    if (!clean || clean.split(' ').length > 4) {
        return null;
    }
    const rule = RULES.find((r) => r.re.test(clean));
    return rule ? rule.reply : null;
}
